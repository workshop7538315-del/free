// 色とマナ総量ごとの型。[P, T, キーワード] を2通り(番号の偶奇で選ぶ)
const DISHA_SHAPES = {
  W: { 1: [[1, 2, ["警戒"]], [1, 1, ["絆魂"]]], 2: [[2, 2, ["先制攻撃"]], [2, 3, []]], 3: [[3, 3, ["警戒"]], [2, 4, ["絆魂"]]] },
  U: { 1: [[1, 1, ["飛行"]], [0, 3, []]], 2: [[1, 3, []], [2, 1, ["飛行"]]], 3: [[2, 3, ["飛行"]], [2, 4, ["呪禁"]]] },
  G: { 1: [[2, 1, []], [1, 2, ["到達"]]], 2: [[2, 2, ["到達"]], [3, 2, []]], 3: [[3, 3, ["トランプル"]], [4, 3, []]] },
  multi: { 2: [[2, 2, ["警戒"]], [2, 3, []]], 3: [[3, 3, ["飛行"]], [3, 3, ["速攻"]]] },
};
const dishaMV = (n, color) => (color.length > 1 ? 2 + (n % 2) : (n % 3) + 1);
function dishaCost(n, color) {
  const mv = dishaMV(n, color);
  const pips = color.split("").map((c) => `{${c}}`).join("");
  const generic = mv - color.length;
  return (generic > 0 ? `{${generic}}` : "") + pips;
}
function dishaShape(n, color) {
  const table = color.length > 1 ? DISHA_SHAPES.multi : DISHA_SHAPES[color];
  return table[dishaMV(n, color)][Math.floor(n / 3) % 2];
}

const genHero = (n, name, cost, star, p, t, kws) => ({
  ...cr(id(n), name, cost, star, p, t, "C", kws.length ? [kw(...kws)] : []),
  rarity: "生成",
  tags: ["梁山泊"],
});

export const SUIKODEN_GEN = [
  ...GEN_TIANGANG.map(([n, name, cost, p, t, kws]) => genHero(n, name, cost, TG, p, t, kws)),
  ...GEN_DISHA.map(([n, name, color]) => {
    const [p, t, kws] = dishaShape(n, color);
    return genHero(n, name, dishaCost(n, color), TD, p, t, kws);
  }),
];
